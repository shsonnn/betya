import assert from "node:assert/strict";
import { roomTestClient } from "./room-test-client.mjs";
const client = roomTestClient(process.env.BETYA_TEST_ORIGIN || "http://127.0.0.1:4187");
const { create, join, connect } = client;
try {
  const created = await create("bomb"), code = created.body.room.code;
  let host = connect(code, created.cookie);
  await host.next("room.snapshot");
  host.send("game.bomb.start", { round: 0 });
  assert.equal((await host.next("error")).code, "INVALID_STATE");
  const second = await join(code, "둘째"), third = await join(code, "셋째");
  const guest = connect(code, second.cookie), other = connect(code, third.cookie);
  await guest.next("room.snapshot"); await other.next("room.snapshot");
  let peers = new Map([[created.body.player.player_id, host], [second.body.player.player_id, guest], [third.body.player.player_id, other]]);
  guest.send("game.bomb.start", { round: 0 });
  assert.equal((await guest.next("error")).code, "FORBIDDEN");
  host.send("game.bomb.start", { round: 0 });
  let game = (await host.next("game.updated", p => p.game.bomb.phase === "countdown")).game;
  assert.equal("explodes_at_ms" in game.bomb, false);
  assert.equal(game.bomb.participant_ids.length, 3);
  host.send("game.reset");
  assert.equal((await host.next("error")).code, "INVALID_STATE");
  host.send("game.switch", { game_type: "roulette" });
  assert.equal((await host.next("error")).code, "INVALID_STATE");
  const holder = peers.get(game.bomb.holder_id);
  const target = [...peers.keys()].find(id => id !== game.bomb.holder_id);
  holder.send("game.bomb.pass", { player_id: target, round: 1, turn: 0 });
  assert.equal((await holder.next("error")).code, "INVALID_STATE");
  game = (await host.next("game.updated", p => p.game.bomb.phase === "playing")).game;
  assert.equal("explodes_at_ms" in game.bomb, false);
  holder.send("game.bomb.pass", { player_id: target, round: 1, turn: 0 });
  assert.equal((await holder.next("error")).code, "INVALID_STATE");
  const lateJoined = await join(code, "늦게 온 친구"), late = connect(code, lateJoined.cookie);
  assert.equal((await late.next("room.snapshot")).game.bomb.participant_ids.includes(lateJoined.body.player.player_id), false);
  await new Promise(resolve => setTimeout(resolve, Math.max(0, game.bomb.pass_available_at_ms - Date.now() + 30)));
  const nonholder = [...peers.entries()].find(([id]) => id !== game.bomb.holder_id)[1];
  nonholder.send("game.bomb.pass", { player_id: game.bomb.holder_id, round: 1, turn: 0 });
  assert.equal((await nonholder.next("error")).code, "INVALID_STATE");
  holder.send("game.bomb.pass", { player_id: lateJoined.body.player.player_id, round: 1, turn: 0 });
  assert.equal((await holder.next("error")).code, "INVALID_STATE");
  holder.send("game.bomb.pass", { player_id: target, round: 1, turn: 0 });
  game = (await host.next("game.updated", p => p.game.bomb.turn === 1)).game;
  assert.equal(game.bomb.holder_id, target);
  assert.equal("explodes_at_ms" in game.bomb, false);
  holder.send("game.bomb.pass", { player_id: target, round: 1, turn: 0 });
  assert.equal((await holder.next("error")).code, "INVALID_STATE");
  host = connect(code, created.cookie);
  const restored = await host.next("room.snapshot");
  assert.equal(restored.game.bomb.holder_id, target);
  assert.equal("explodes_at_ms" in restored.game.bomb, false);
  peers.set(created.body.player.player_id, host);
  const exploded = await host.next("game.updated", p => p.game.bomb.phase === "finished", 29_000);
  assert.deepEqual(exploded.game.bomb.result, { loser_id: target, reason: "exploded" });
  assert.deepEqual((await late.next("game.updated", p => p.game.bomb.phase === "finished")).game, exploded.game);
  host.send("game.bomb.start", { round: 1 });
  const rematch = await host.next("game.updated", p => p.game.bomb.round === 2 && p.game.bomb.phase === "countdown");
  assert.equal(rematch.game.bomb.participant_ids.length, 4);
  const memberships = new Map([[created.body.player.player_id, created], [second.body.player.player_id, second], [third.body.player.player_id, third], [lateJoined.body.player.player_id, lateJoined]]);
  const currentHolder = rematch.game.bomb.holder_id;
  // Preserve the host so it can inspect the result even if it was selected initially.
  if (currentHolder === created.body.player.player_id) {
    await host.next("game.updated", p => p.game.bomb.round === 2 && p.game.bomb.phase === "playing");
    await new Promise(resolve => setTimeout(resolve, Math.max(0, rematch.game.bomb.pass_available_at_ms - Date.now() + 30)));
    host.send("game.bomb.pass", { player_id: second.body.player.player_id, round: 2, turn: 0 });
    await host.next("game.updated", p => p.game.bomb.round === 2 && p.game.bomb.turn === 1);
  }
  const leavingId = currentHolder === created.body.player.player_id ? second.body.player.player_id : currentHolder;
  assert.equal((await client.post(`/api/rooms/${code}/leave`, {}, memberships.get(leavingId).cookie)).status, 200);
  const departed = await host.next("game.updated", p => p.game.bomb.round === 2 && p.game.bomb.phase === "finished");
  assert.deepEqual(departed.game.bomb.result, { loser_id: leavingId, reason: "left" });
  host.send("game.switch", { game_type: "rps" });
  assert.equal((await host.next("game.switched")).game.type, "rps");
  console.log("PASS: bomb permissions, hidden fuse, countdown, cooldown, holder-only passing, late joins, replay protection, reconnect, automatic detonation, rematch, leaving, and game switching");
} finally { await client.close(); }
